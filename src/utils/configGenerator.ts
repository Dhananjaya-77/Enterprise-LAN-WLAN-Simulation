import { Device, Link, VLAN } from '../types/network';

export function generateCiscoIosConfig(device: Device, vlans: VLAN[], links: Link[]): string {
  const lines: string[] = [];

  lines.push(`! ========================================================`);
  lines.push(`! CISCO IOS CONFIGURATION FOR: ${device.hostname.toUpperCase()}`);
  lines.push(`! Model: ${device.model} | Role: ${device.roleDescription}`);
  lines.push(`! Generated by Enterprise LAN/WLAN Simulator`);
  lines.push(`! ========================================================`);
  lines.push(`version 15.2`);
  lines.push(`service timestamps debug datetime msec`);
  lines.push(`service timestamps log datetime msec`);
  lines.push(`service password-encryption`);
  lines.push(`!`);
  lines.push(`hostname ${device.hostname}`);
  lines.push(`!`);
  lines.push(`ip domain-name enterprise.corp`);
  lines.push(`crypto key generate rsa modulus 2048`);
  lines.push(`ip ssh version 2`);
  lines.push(`!`);
  lines.push(`enable secret 9 $9$EnterpriseAdminSecretKey!`);
  lines.push(`!`);
  lines.push(`username admin privilege 15 secret 9 $9$EnterpriseAdminSecretKey!`);
  lines.push(`!`);

  // Multilayer Switch / Router SVI & Routing
  if (device.type === 'core_switch' || device.type === 'dist_switch' || device.type === 'router') {
    lines.push(`! --- Inter-VLAN Routing & SVIs ---`);
    lines.push(`ip routing`);
    lines.push(`!`);

    for (const vlan of vlans) {
      lines.push(`vlan ${vlan.id}`);
      lines.push(` name ${vlan.name.replace(/\s+/g, '_').toUpperCase()}`);
      lines.push(`!`);
      lines.push(`interface Vlan${vlan.id}`);
      lines.push(` description SVI Gateway for ${vlan.name}`);
      lines.push(` ip address ${vlan.gateway} ${vlan.subnetMask}`);
      lines.push(` ip helper-address 10.100.99.10`); // Enterprise DHCP Relay
      lines.push(` no shutdown`);
      lines.push(`!`);
    }

    // DHCP Pools if core
    if (device.type === 'core_switch') {
      lines.push(`! --- Centralized Campus DHCP Pools ---`);
      for (const vlan of vlans) {
        if (vlan.id === 1) continue;
        lines.push(`ip dhcp excluded-address ${vlan.gateway} ${vlan.gateway.replace(/\.\d+$/, '.10')}`);
        lines.push(`ip dhcp pool POOL_VLAN_${vlan.id}_${vlan.name.replace(/\s+/g, '_')}`);
        lines.push(` network ${vlan.subnet} ${vlan.subnetMask}`);
        lines.push(` default-router ${vlan.gateway}`);
        lines.push(` dns-server 10.100.99.10 8.8.8.8`);
        lines.push(` domain-name enterprise.corp`);
        lines.push(` lease 7 0 0`);
        lines.push(`!`);
      }
    }
  } else if (device.type === 'access_switch') {
    lines.push(`! --- Layer 2 VLAN Database ---`);
    for (const vlan of vlans) {
      lines.push(`vlan ${vlan.id}`);
      lines.push(` name ${vlan.name.replace(/\s+/g, '_').toUpperCase()}`);
    }
    lines.push(`!`);
    lines.push(`interface Vlan10`);
    lines.push(` description Management Interface`);
    lines.push(` ip address ${device.interfaces[0]?.ip || '10.100.10.20'} 255.255.255.0`);
    lines.push(` no shutdown`);
    lines.push(`!`);
    lines.push(`ip default-gateway 10.100.10.1`);
    lines.push(`!`);
  }

  // Interface configurations
  lines.push(`! --- Physical & Trunk Interfaces ---`);
  device.interfaces.forEach((iface, index) => {
    lines.push(`interface ${iface.name}`);
    lines.push(` description Connected to Enterprise Fabric`);

    if (iface.mode === 'trunk') {
      lines.push(` switchport trunk encapsulation dot1q`);
      lines.push(` switchport mode trunk`);
      lines.push(` switchport trunk native vlan ${iface.nativeVlan || 99}`);
      lines.push(` switchport trunk allowed vlan 10,20,30,40,50,60,99`);
      lines.push(` switchport nonegotiate`);
    } else if (iface.mode === 'access') {
      lines.push(` switchport mode access`);
      lines.push(` switchport access vlan ${iface.vlanId || 10}`);
      lines.push(` spanning-tree portfast`);
      lines.push(` spanning-tree bpduguard enable`);
    } else if (iface.mode === 'routed') {
      lines.push(` no switchport`);
      lines.push(` ip address ${iface.ip || '10.100.1.1'} ${iface.subnetMask || '255.255.255.252'}`);
    }

    lines.push(` no shutdown`);
    lines.push(`!`);
  });

  // Wireless LAN Controller (WLC) specific configuration
  if (device.type === 'wlc') {
    lines.push(`! --- Cisco Catalyst 9800 WLC Configuration ---`);
    lines.push(`wireless management interface GigabitEthernet0/1`);
    lines.push(`wireless tag rf CAMPUS-RF-POLICY`);
    lines.push(`!`);
    lines.push(`wlan Corp-Secure-WLAN 1 Corp-Secure-WLAN`);
    lines.push(` client vlan 30`);
    lines.push(` security wpa psk set-key ascii 0 EnterpriseCorpKey2026!`);
    lines.push(` security wpa wpa3`);
    lines.push(` radio dot11a`);
    lines.push(` radio dot11b`);
    lines.push(` no shutdown`);
    lines.push(`!`);
    lines.push(`wlan Guest-WLAN 2 Guest-WLAN`);
    lines.push(` client vlan 40`);
    lines.push(` security web-auth`);
    lines.push(` no shutdown`);
    lines.push(`!`);
    lines.push(`ap profile CAMPUS-AP-PROFILE`);
    lines.push(` capwap preferred-mode ipv4`);
    lines.push(` hyperlocation enable`);
    lines.push(`!`);
  }

  // Access-Lists (ACL)
  if (device.aclRules && device.aclRules.length > 0) {
    lines.push(`! --- Security Access Control Lists (ACL) ---`);
    lines.push(`ip access-list extended ENTERPRISE-SECURITY-POLICY`);
    for (const rule of device.aclRules) {
      const line = ` ${rule.action} ${rule.protocol} ${rule.sourceNetwork} ${rule.sourceWildcard} ${rule.destNetwork} ${rule.destWildcard}${rule.destPort ? ' eq ' + rule.destPort : ''}`;
      lines.push(line);
    }
    lines.push(` permit ip any any`);
    lines.push(`!`);
  }

  // Spanning-Tree & Line configs
  lines.push(`spanning-tree mode rapid-pvst`);
  lines.push(`spanning-tree extend system-id`);
  lines.push(`!`);
  lines.push(`line con 0`);
  lines.push(` logging synchronous`);
  lines.push(` login local`);
  lines.push(`line vty 0 15`);
  lines.push(` transport input ssh`);
  lines.push(` login local`);
  lines.push(`!`);
  lines.push(`end`);
  lines.push(`write memory`);

  return lines.join('\n');
}

export function generateArubaOsConfig(device: Device, vlans: VLAN[]): string {
  const lines: string[] = [];
  lines.push(`; ========================================================`);
  lines.push(`; ARUBA CX CONFIGURATION FOR: ${device.hostname.toUpperCase()}`);
  lines.push(`; ========================================================`);
  lines.push(`hostname ${device.hostname}`);
  lines.push(`ssh server vrf default`);
  lines.push(`!`);

  for (const vlan of vlans) {
    lines.push(`vlan ${vlan.id}`);
    lines.push(`    name ${vlan.name.replace(/\s+/g, '_')}`);
    lines.push(`interface vlan ${vlan.id}`);
    lines.push(`    ip address ${vlan.gateway}/${vlan.cidr}`);
    lines.push(`    ip helper-address 10.100.99.10`);
  }

  lines.push(`!`);
  lines.push(`interface 1/1/1`);
  lines.push(`    no shutdown`);
  lines.push(`    vlan trunk native 99`);
  lines.push(`    vlan trunk allowed 10,20,30,40,50,60,99`);
  lines.push(`!`);

  return lines.join('\n');
}
